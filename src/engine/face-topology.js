/** دیکود base64 → Uint8Array بدون وابستگی به Buffer (مرورگر و Node) */
function b64bytes(text) {
  const clean = text.replace(/\s+/g, "");
  if (typeof atob === "function") {
    const bin = atob(clean);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }
  const buf = typeof Buffer !== "undefined" ? Buffer.from(clean, "base64") : null;
  if (!buf) throw new Error("base64 decoder unavailable");
  return new Uint8Array(buf.buffer, buf.byteOffset, buf.length);
}

function decodeVerts() {
  const bytes = b64bytes(B64.v);
  const raw = new Int16Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 2);
  const out = new Float32Array(raw.length);
  for (let i = 0; i < raw.length; i++) out[i] = raw[i] / 10; // دهمِ میلی‌متر ⇒ میلی‌متر
  return out;
}

function decodeTris() {
  const bytes = b64bytes(B64.t);
  return new Uint16Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 2);
}

/** مختصاتِ کانونیکِ ۴۶۸ رأس به میلی‌متر (x,y,z پشت‌سرهم) */
export const CANONICAL_MM = decodeVerts();
/** مثلث‌های توپولوژیِ FaceMesh (۸۹۸×۳ ایندکس) */
export const FACE_TRIS = decodeTris();

/** اندازه‌های مدلِ کانونیک — برای نرمال‌سازی و کنترلِ سلامتِ داده */
export const CANONICAL_METRICS = (() => {
  const d = (a, b) =>
    Math.hypot(
      CANONICAL_MM[a * 3] - CANONICAL_MM[b * 3],
      CANONICAL_MM[a * 3 + 1] - CANONICAL_MM[b * 3 + 1],
      CANONICAL_MM[a * 3 + 2] - CANONICAL_MM[b * 3 + 2],
    );
  return {
    faceWidth: d(234, 454),
    eyeSpan: d(133, 362),
    eyeOuter: d(33, 263),
    faceHeight: d(10, 152),
    noseBridge: d(168, 6),
    noseTipDepth: CANONICAL_MM[4 * 3 + 2],
    eyeDepth: (CANONICAL_MM[33 * 3 + 2] + CANONICAL_MM[263 * 3 + 2]) / 2,
    vertexCount: CANONICAL_MM.length / 3,
    triangleCount: FACE_TRIS.length / 3,
  };
})();

/** مثلث‌های مجاورِ هر رأس (برای جست‌وجوی نزدیک‌ترین سطح) */
export function vertexTriangles() {
  const count = CANONICAL_METRICS.vertexCount;
  const ring = Array.from({ length: count }, () => []);
  for (let t = 0; t < FACE_TRIS.length; t += 3) {
    for (let k = 0; k < 3; k++) ring[FACE_TRIS[t + k]].push(t / 3);
  }
  return ring;
}
